import assert from 'node:assert/strict';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { workspaceRoot } from './sources.mjs';

const plugin = resolve(workspaceRoot, 'dist/packages/nativescript-mason-core');
const output = resolve(workspaceRoot, 'tmp/mason-core-nativescript-consumer');
const marker = resolve(output, '.mason-core-consumer');
if (existsSync(output)) assert.ok(existsSync(marker), 'Refusing to overwrite an unowned consumer directory.');
mkdirSync(output, { recursive: true });
writeFileSync(marker, 'Private core-only NativeScript consumer generated by tools/mason-core/prepare-consumer.mjs\n');
rmSync(resolve(output, 'consumer-scenario.json'), { force: true });
// The Vite qualification uses the same owned fixture. Restore the baseline's
// configuration when switching back to its Webpack scenarios.
for (const name of ['nativescript.config.ts', 'vite.config.mts']) rmSync(resolve(output, name), { force: true });
function write(name, text) {
  const filename = resolve(output, name);
  mkdirSync(dirname(filename), { recursive: true });
  writeFileSync(filename, text);
}
const packed = spawnSync('pnpm', ['pack', '--pack-destination', output], { cwd: plugin, encoding: 'utf8' });
if (packed.error) throw packed.error;
if (packed.status !== 0) throw new Error(`Plugin pack failed:\n${packed.stdout}\n${packed.stderr}`);
const pluginManifest = JSON.parse(readFileSync(resolve(plugin, 'package.json'), 'utf8'));
assert.equal(pluginManifest.name, '@octane-xplat/nativescript-mason-core');
const tarball = 'octane-xplat-nativescript-mason-core-0.0.0.tgz';
assert.ok(existsSync(resolve(output, tarball)));
write('package.json', JSON.stringify({
  name: 'mason-core-native-consumer', version: '0.0.0', private: true, main: './app/app.js',
  packageManager: JSON.parse(readFileSync(resolve(workspaceRoot, 'package.json'), 'utf8')).packageManager,
  dependencies: {
    '@nativescript/core': '9.1.2',
    '@octane-xplat/nativescript-mason-core': `file:./${tarball}`,
  },
  devDependencies: {
    '@nativescript/android': '9.1.1', '@nativescript/ios': '9.1.0',
    '@nativescript/webpack': '5.0.38', nativescript: '9.1.1',
  },
}, null, 2) + '\n');
// Establish a separate pnpm project: no workspace links or incidental full plugin.
write('pnpm-workspace.yaml', `packages: []
autoInstallPeers: false
allowBuilds:
  '@nativescript/core': true
  '@parcel/watcher': true
  core-js-pure: true
  nativescript: true
`);
write('nativescript.config.js', `module.exports = {
  id: 'org.octane.masoncoreprobe', appPath: 'app', appResourcesPath: 'App_Resources',
  cli: { packageManager: 'pnpm' },
};\n`);
copyFileSync(resolve(workspaceRoot, 'tools/mason-core/consumer/webpack.config.js'), resolve(output, 'webpack.config.js'));
mkdirSync(resolve(output, 'app'), { recursive: true });
copyFileSync(resolve(workspaceRoot, 'tools/mason-core/consumer/app.js'), resolve(output, 'app/app.js'));
write('App_Resources/iOS/Info.plist', `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>CFBundleDisplayName</key><string>Mason core probe</string>
<key>CFBundleExecutable</key><string>\${EXECUTABLE_NAME}</string>
<key>CFBundleIdentifier</key><string>\${PRODUCT_BUNDLE_IDENTIFIER}</string>
<key>CFBundleName</key><string>\${PRODUCT_NAME}</string>
<key>CFBundlePackageType</key><string>APPL</string>
<key>CFBundleShortVersionString</key><string>1.0</string>
<key>CFBundleVersion</key><string>1</string>
<key>UIApplicationSceneManifest</key><dict><key>UIApplicationSupportsMultipleScenes</key><false/></dict>
<key>UILaunchScreen</key><dict/>
<key>UISupportedInterfaceOrientations</key><array><string>UIInterfaceOrientationPortrait</string></array>
</dict></plist>\n`);
write('App_Resources/iOS/build.xcconfig', 'IPHONEOS_DEPLOYMENT_TARGET = 15.6\nTARGETED_DEVICE_FAMILY = 1,2\nARCHS = arm64\n');
write('App_Resources/Android/src/main/AndroidManifest.xml', `<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
  <uses-permission android:name="android.permission.INTERNET"/>
  <application android:name="com.tns.NativeScriptApplication" android:label="Mason core probe" android:theme="@style/AppTheme">
    <activity android:name="com.tns.NativeScriptActivity" android:exported="true"
      android:configChanges="keyboard|keyboardHidden|orientation|screenSize|smallestScreenSize|screenLayout|locale|uiMode">
      <intent-filter><action android:name="android.intent.action.MAIN"/><category android:name="android.intent.category.LAUNCHER"/></intent-filter>
    </activity>
    <activity android:name="com.tns.ErrorReportActivity"/>
  </application>
</manifest>\n`);
write('App_Resources/Android/src/main/res/values/styles.xml', `<resources>
  <style name="AppThemeBase" parent="Theme.AppCompat.Light.NoActionBar"/>
  <style name="AppTheme" parent="AppThemeBase"/>
  <style name="NativeScriptToolbarStyleBase" parent="Widget.AppCompat.Toolbar"/>
  <style name="NativeScriptToolbarStyle" parent="NativeScriptToolbarStyleBase"/>
</resources>\n`);
write('App_Resources/Android/app.gradle', 'android { defaultConfig { ndk { abiFilters.clear(); abiFilters "arm64-v8a" } } }\n');
console.log(`Prepared ${output}. Install with pnpm install; native build/run requires resource reservations.`);
