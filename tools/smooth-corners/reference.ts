// Run: bun tools/smooth-corners/reference.ts /path/to/octane-xplat /path/to/lisse/packages/core
// Reads the authoritative framework source; installs no dependency and changes no consumer.
import { mkdtempSync, readFileSync, writeFileSync, copyFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { createHash } from 'node:crypto'
import assert from 'node:assert/strict'
import { resolve } from 'node:path'
const [framework,lisse] = process.argv.slice(2)
if (!framework || !lisse) throw Error('Pass framework checkout and pinned Lisse 0.7.3 core source')
const stage = mkdtempSync(resolve(tmpdir(),'mason-corner-reference-'))
const source=resolve(framework,'packages/smooth-corners/src')
const hashes = {
  'path.ts': '094e143783abff467bf61aa82d52988baf91573d9aeb6ac49d777623bc598bb5',
  'props.ts': 'c8ee6e8320aca61e870813b27013bdc2f70737916503a9ed447e7ee71921ee7a',
  'validation.ts': '71dbe75d72f2763a26acbcdf90fd97990ca42d49ef0f618dbf520f49ebbc03b4',
}
for (const [name, hash] of Object.entries(hashes)) assert.equal(createHash('sha256').update(readFileSync(resolve(source,name))).digest('hex'), hash, `Reference ${name} changed`)
assert.equal(JSON.parse(readFileSync(resolve(lisse,'package.json'),'utf8')).version,'0.7.3')
for (const name of ['props.ts','validation.ts']) copyFileSync(resolve(source,name),resolve(stage,name))
writeFileSync(resolve(stage,'path.ts'),readFileSync(resolve(source,'path.ts'),'utf8').replaceAll("'@lisse/core/path'",JSON.stringify(resolve(lisse,'src/path.ts'))))
const {generateCommands}=await import(resolve(stage,'path.ts'))
const curves=['continuous','squircle','superellipse','clothoid','arc']
let seed=1234567
const random=()=>{seed=(Math.imul(seed,1664525)+1013904223)>>>0;return seed/2**32}
const cases:any[]=[]
for (const curve of curves) for (const [w,h,r] of [[240,120,24],[40,40,100],[200,40,60],[40,200,60],[100,55,20],[0,40,20],[0,0,0],[1,0.5,100],[0.0001,0.0002,0.00001],[100,100,0]]) for (const smoothing of [0,0.65,1]) for (const preserveSmoothing of [false,true]) for (const exponent of [2,4,8]) {
 cases.push([w,h,Array(4).fill({radius:r,curve,smoothing,exponent,preserveSmoothing})])
}
for(let i=0;i<300;i++) cases.push([random()*300+0.1,random()*300+0.1,curves.slice(0,4).map(()=>({radius:random()*250,curve:curves[Math.floor(random()*5)],smoothing:random(),exponent:2+random()*6,preserveSmoothing:random()>0.5}))])
const packed=(c:any)=>c.c==='M'||c.c==='L'?[c.c==='M'?0:1,c.x,c.y,0,0,0,0,0]:c.c==='C'?[2,c.x1,c.y1,c.x2,c.y2,c.x,c.y,0]:c.c==='A'?[3,c.cx,c.cy,c.r,c.startDeg,c.sweepDeg,c.x,c.y]:[4,0,0,0,0,0,0,0]
let output='# Reference: Octane 862b67ba3dc215711b20ad9c45f7b1b58d57619f; @lisse/core 0.7.3. Generated by tools/smooth-corners/reference.ts\n'
for(const [w,h,c] of cases){
 const options={topLeft:c[0],topRight:c[1],bottomRight:c[2],bottomLeft:c[3]}
 const commands=generateCommands(w,h,options)
 output+='case '+[w,h,...c.flatMap((v:any)=>[v.radius,curves.indexOf(v.curve),v.smoothing,v.exponent,+v.preserveSmoothing])].join(' ')+'\n'
 output+=commands.map((v:any)=>packed(v).join(' ')).join('\n')+'\n'
}
writeFileSync('crates/mason-core/tests/fixtures/smooth-corners.txt',output)
rmSync(stage, { recursive: true })
console.log(`${cases.length} reference cases`)
